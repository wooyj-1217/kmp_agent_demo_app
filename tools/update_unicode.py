"""Generate common Kotlin tables from pinned official Unicode 16 data."""
from pathlib import Path
from urllib.request import urlopen
import hashlib
import json

root = Path(__file__).resolve().parents[1]
folder = root / "third-party/unicode-16"
folder.mkdir(parents=True, exist_ok=True)
sources = {
    "GraphemeBreakProperty.txt": "https://www.unicode.org/Public/16.0.0/ucd/auxiliary/GraphemeBreakProperty.txt",
    "GraphemeBreakTest.txt": "https://www.unicode.org/Public/16.0.0/ucd/auxiliary/GraphemeBreakTest.txt",
    "emoji-data.txt": "https://www.unicode.org/Public/16.0.0/ucd/emoji/emoji-data.txt",
    "DerivedCoreProperties.txt": "https://www.unicode.org/Public/16.0.0/ucd/DerivedCoreProperties.txt",
    "LICENSE.txt": "https://www.unicode.org/license.txt",
}
manifest = {}
for name, url in sources.items():
    target = folder / name
    if not target.exists(): target.write_bytes(urlopen(url, timeout=40).read())
    manifest[name] = {"url": url, "sha256": hashlib.sha256(target.read_bytes()).hexdigest()}
(folder / "sources.json").write_text(json.dumps(manifest, indent=2) + "\n")
tables = {}
for file, field in [("GraphemeBreakProperty.txt", "grapheme"), ("emoji-data.txt", "pictographic"), ("DerivedCoreProperties.txt", "indic")]:
    for line in (folder / file).read_text().splitlines():
        fields = [f.strip() for f in line.split("#")[0].split(";")]
        if len(fields) < 2: continue
        if field == "pictographic" and fields[1] != "Extended_Pictographic": continue
        if field == "indic" and (fields[1] != "InCB" or len(fields) < 3): continue
        name = fields[2] if field == "indic" else fields[1]
        bounds = fields[0].split("..")
        tables.setdefault((field, name), []).append((int(bounds[0], 16), int(bounds[-1], 16)))
out = ["// Generated by tools/update_unicode.py. Unicode 16.0; see third-party/unicode-16/LICENSE.txt.", "package memo.domain", "internal object Unicode16 {", "    private fun contains(p: Int, ranges: IntArray): Boolean {", "        var low = 0; var high = ranges.size / 2 - 1", "        while (low <= high) { val mid = (low + high) / 2; val start = ranges[mid * 2]; val end = ranges[mid * 2 + 1]", "            if (p < start) high = mid - 1 else if (p > end) low = mid + 1 else return true }", "        return false", "    }"]
for (field, name), ranges in sorted(tables.items()):
    identifier = field + name
    values = [hex(v) for bounds in sorted(ranges) for v in bounds]
    out.append(f"    private val {identifier} = intArrayOf(")
    out.extend("        " + ",".join(values[i:i+20]) + "," for i in range(0, len(values), 20))
    out.append("    )")
for field in ["grapheme", "indic"]:
    out.append(f"    fun {field}(p: Int): String = when {{")
    out.extend(f'        contains(p, {f}{name}) -> "{name}"' for f, name in sorted(tables) if f == field)
    out.extend(['        else -> "Other"', "    }"])
out.extend(["    fun pictographic(p: Int) = contains(p, pictographicExtended_Pictographic)", "}"])
target = root / "shared/src/commonMain/kotlin/memo/domain/Unicode16.kt"
target.write_text("\n".join(out) + "\n")
fixture = root / "shared/src/jvmTest/resources/GraphemeBreakTest.txt"
fixture.parent.mkdir(parents=True, exist_ok=True)
fixture.write_bytes((folder / "GraphemeBreakTest.txt").read_bytes())
print("Generated Unicode16 tables from", len(tables), "property sets; source hashes in", folder / "sources.json")
